#!/usr/bin/env node
/**
 * Security Documentation Sanitizer
 * 
 * Removes all exposed credentials from documentation files
 * Run: node .security-sanitize-docs.js
 */

const fs = require('fs');
const path = require('path');

const DOCS_TO_SANITIZE = [
  'ADMIN_LOGIN_FIX.md',
  'DEPLOY_NOW.md', 
  'DEPLOYMENT_SUMMARY.md',
  'FIX_RENDER_ENV_VARS.md',
  'PRODUCTION_STATUS.md',
  'FINAL_STATUS.md',
  'READY_FOR_OWNER.md',
  'URGENT_DEPLOY_INSTRUCTIONS.md',
  'RENDER_DEPLOYMENT_GUIDE.md',
  'PRODUCTION_READINESS_CHECKLIST.md',
  'README.md',
  'PRODUCTION_RECOVERY_REPORT.md'
];

const REPLACEMENTS = [
  // Admin password
  { pattern: /Bu@240708/g, replacement: '[ADMIN_PASSWORD - Set in Render Dashboard]' },
  
  // Database URLs with credentials
  { pattern: /postgresql:\/\/neondb_owner:npg_[^@]+@[^\s\n"'`]+/g, replacement: 'postgresql://[REDACTED]' },
  
  // JWT secrets
  { pattern: /murugesan-prod-jwt-secret-[a-f0-9]+/g, replacement: '[JWT_SECRET - Auto-generated by Render]' },
  { pattern: /dev-secret-change-before-production-[a-f0-9]+/g, replacement: '[JWT_SECRET - Use env var]' },
  
  // Generic credential patterns
  { pattern: /password:\s*["']Bu@240708["']/gi, replacement: 'password: "[REDACTED]"' },
  { pattern: /password\s*=\s*Bu@240708/gi, replacement: 'password=[REDACTED]' }
];

console.log('🔒 Starting security documentation sanitization...\n');

let totalReplacements = 0;
let filesModified = 0;

for (const docFile of DOCS_TO_SANITIZE) {
  const filePath = path.join(__dirname, docFile);
  
  if (!fs.existsSync(filePath)) {
    console.log(`⚠️  Skipping ${docFile} (not found)`);
    continue;
  }
  
  let content = fs.readFileSync(filePath, 'utf8');
  let fileReplacements = 0;
  
  for (const { pattern, replacement } of REPLACEMENTS) {
    const matches = content.match(pattern);
    if (matches) {
      fileReplacements += matches.length;
      content = content.replace(pattern, replacement);
    }
  }
  
  if (fileReplacements > 0) {
    fs.writeFileSync(filePath, content, 'utf8');
    console.log(`✅ ${docFile}: ${fileReplacements} credential(s) removed`);
    filesModified++;
    totalReplacements += fileReplacements;
  } else {
    console.log(`✓  ${docFile}: already clean`);
  }
}

console.log(`\n🎉 Sanitization complete!`);
console.log(`   Files modified: ${filesModified}`);
console.log(`   Total credentials removed: ${totalReplacements}`);
console.log(`\n⚠️  IMPORTANT: You must now rotate all exposed credentials:`);
console.log(`   1. Change ADMIN_PASSWORD in Render dashboard`);
console.log(`   2. Rotate PostgreSQL database password in Neon`);
console.log(`   3. Regenerate JWT_SECRET in Render (users will need to re-login)`);
console.log(`\n   See SECURITY_AUDIT_REPORT.md for details`);
